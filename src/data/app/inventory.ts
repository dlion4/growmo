/** Deterministic 6-month price walk around a base price (Jun → Nov 2026). */
const TREND_SHAPE = [-0.06, -0.025, 0.012, 0.045, 0.02, 0.07];

function priceHistory(base: number, seed: number): number[] {
  return TREND_SHAPE.map((shape, index) => {
    const wobble = ((((seed * 7 + index * 13) % 11) - 5) / 100) * 0.5;
    return Math.round((base * (1 + shape + wobble)) / 10) * 10;
  });
}

