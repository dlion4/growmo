/** Cheapest offer across the supplier directory for a catalog item. */
export function bestOffer(itemId: string): {
  supplier: Supplier;
  offer: SupplierOffer;
} | null {
  let best: { supplier: Supplier; offer: SupplierOffer } | null = null;
  for (const supplier of SUPPLIERS) {
    for (const offer of supplier.offers) {
      if (offer.itemId !== itemId || offer.stock < 1) continue;
      if (!best || offer.price < best.offer.price) {
        best = { supplier, offer };
      }
    }
  }
  return best;
}

/** Every offer for an item, cheapest first — powers the compare modal. */
export function offersFor(itemId: string): {
  supplier: Supplier;
  offer: SupplierOffer;
}[] {
  return SUPPLIERS.flatMap((supplier) =>
    supplier.offers
      .filter((offer) => offer.itemId === itemId)
      .map((offer) => ({ supplier, offer })),
  ).sort((a, b) => a.offer.price - b.offer.price);
}
